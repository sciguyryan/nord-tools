"""Startup unit rendering, installation and durable boot reconciliation records.

The systemd integration plays one narrow part in the wider design: it invokes the
privileged boot restoration command after the network has come online, and
records what each boot did. Rendering is deterministic so that repeated
installations and repeated boot runs are idempotent. Installing files on the
user's own host is the only side effect this module permits, and only when an
existing file was previously generated by this installer.

Transient intent is structurally unreachable from these artefacts: every
rendered unit references the startup configuration, which carries only
persistent paths, and the boot command refuses transient scope itself.
"""

from __future__ import annotations

from contextlib import contextmanager
import fcntl
import json
import os
from pathlib import Path
import re
import stat
import tempfile
from typing import Iterator

from nord_tools_internal.nordvpn_registry import RegistryError

SERVICE_UNIT = "nord-tools-restore.service"
# Local, generated unit and store files carry this marker so foreign files are
# never replaced or overwritten by a concurrent unrelated installation.
_GENERATED_MARKER = "# Managed by Nord Tools manage startup-install; regenerate rather than editing."
# A civilised Linux filesystem path without shell, systemd or JSON hazards:
# whitespace, quotes and control characters are refused rather than escaped.
_PATH = re.compile(r"/[A-Za-z0-9._/-]+\Z")
_BOOT_ID = re.compile(r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\Z")
_BOOT_ID_PATH = "/proc/sys/kernel/random/boot_id"
# Run records are appends of one entry per boot attempt; the cap keeps the file
# finite and makes an unbounded takeover of the recording path fail loudly.
MAX_RUNS = 512
SERVICE_NAME = "nord-tools-restore"


def _validate_path(value: object, field: str) -> str:
    if not isinstance(value, str) or not _PATH.fullmatch(value):
        raise RegistryError(f"{field} must be an absolute path using only /, letters, digits, ., _ and -: {value!r}")
    return value


def _validate_tunnel_plan(name: str, plan: object) -> dict:
    """Validate one pinned provider tunnel per profile; no credentials here.

    The plan is the operator's authoritative pin of provider data: it must
    already contain numeric, unambiguous endpoint and addressing data, because
    the boot path performs neither server selection nor DNS resolution.
    """
    allowed = {
        "peer_public_key",
        "endpoint_address",
        "endpoint_port",
        "tunnel_address",
        "peer_allowed_ips",
        "underlay",
        "dns_servers",
    }
    if not isinstance(name, str) or not re.fullmatch(r"[a-z][a-z0-9_-]{0,63}", name):
        raise RegistryError("invalid profile name in startup configuration")
    if not isinstance(plan, dict) or not (allowed - {"dns_servers"}) <= set(plan) or set(plan) - allowed:
        raise RegistryError(
            f"tunnel plan for {name} requires peer_public_key, endpoint_address, endpoint_port, "
            "tunnel_address, peer_allowed_ips and underlay"
        )
    if not isinstance(plan["peer_public_key"], str):
        raise RegistryError(f"tunnel plan for {name} requires a peer public key string")
    for field in ("endpoint_address", "tunnel_address"):
        if not isinstance(plan[field], str) or not plan[field]:
            raise RegistryError(f"tunnel plan for {name} requires a textual {field}")
    if type(plan["endpoint_port"]) is not int or not 1 <= plan["endpoint_port"] <= 65535:
        raise RegistryError(f"tunnel plan for {name} requires a valid endpoint port")
    if not isinstance(plan["peer_allowed_ips"], list) or any(
        not isinstance(item, str) or not item for item in plan["peer_allowed_ips"]
    ):
        raise RegistryError(f"tunnel plan for {name} requires a list of allowed IP networks")
    underlay = plan["underlay"]
    if not isinstance(underlay, dict) or set(underlay) != {"namespace_address", "host_address"}:
        raise RegistryError(f"tunnel plan for {name} underlay requires namespace_address and host_address")
    for field in ("namespace_address", "host_address"):
        if not isinstance(underlay[field], str) or not underlay[field]:
            raise RegistryError(f"tunnel plan for {name} underlay requires a textual {field}")
    # DNS is opt-in for legacy configurations. New plans must supply a
    # validated numeric resolver list, never a host-dependent DNS name.
    if "dns_servers" in plan:
        from nord_tools_internal.nordvpn_resolver_policy import NamespaceResolverPolicy

        servers = plan["dns_servers"]
        if not isinstance(servers, list):
            raise RegistryError(f"dns_servers for {name} must be a list of numeric addresses")
        try:
            NamespaceResolverPolicy(tuple(servers))
        except (ValueError, TypeError) as exc:
            raise RegistryError(f"invalid DNS servers for {name}: {exc}") from exc
    return dict(plan)


def validate_startup_config(document: object) -> dict:
    """Validate the version 1 startup configuration as explicit persistent paths.

    Every filesystem location that the boot command and the generated unit need
    is pinned here, so the boot service never depends on an unset environment
    such as ``XDG_CONFIG_HOME``. The desired policy and provider tunnel plans may
    point at files that do not exist yet; the boot command fails closed on any
    missing file at run time.
    """
    allowed = {
        "version",
        "policy",
        "journal",
        "bindings",
        "run_record",
        "intent",
        "graph",
        "tunnels",
        "credentials",
        "handovers",
    }
    required = {"version", "policy", "journal", "bindings", "run_record", "tunnels"}
    if not isinstance(document, dict) or not required <= set(document) or set(document) - allowed:
        raise RegistryError(
            f"startup configuration requires {', '.join(sorted(required))} and only known fields; "
            f"unknown: {', '.join(sorted(set(document or {}) - allowed))}"
        )
    if type(document["version"]) is not int or document["version"] != 1:
        raise RegistryError("startup configuration requires version 1")
    paths = {}
    for field in ("policy", "journal", "bindings", "run_record"):
        paths[field] = _validate_path(document[field], field)
    for field in ("intent", "graph"):
        if document.get(field) is not None:
            paths[field] = _validate_path(document[field], field)
    tunnels = document["tunnels"]
    if not isinstance(tunnels, dict):
        raise RegistryError("startup configuration tunnels must be an object")
    tunnels = {name: _validate_tunnel_plan(name, plan) for name, plan in tunnels.items()}
    credentials = document.get("credentials") or {}
    if not isinstance(credentials, dict):
        raise RegistryError("startup configuration credentials must be an object")
    credentials = {name: _validate_path(value, f"credentials for {name}") for name, value in credentials.items()}
    handovers = document.get("handovers") or {}
    if not isinstance(handovers, dict):
        raise RegistryError("startup configuration handovers must be an object")
    if any(not isinstance(name, str) or not name or len(name) > 256 for name in handovers):
        raise RegistryError("startup handover keys must be non-empty allocation identities")
    handovers = {name: _validate_path(value, f"handover for {name}") for name, value in handovers.items()}
    # Credential entries may outnumber plans (for example after retiring one);
    # a plan without its credential is refused when restoration begins.
    result = {
        "version": 1,
        "policy": paths["policy"],
        "journal": paths["journal"],
        "bindings": paths["bindings"],
        "run_record": paths["run_record"],
        "intent": paths.get("intent"),
        "graph": paths.get("graph"),
        "tunnels": tunnels,
        "credentials": credentials,
    }
    if handovers:
        result["handovers"] = handovers
    return result


def read_boot_id(path: str = _BOOT_ID_PATH) -> str:
    """Read the current boot identity; continuity never spans boot sessions."""
    try:
        with open(path, encoding="ascii") as source:
            boot_id = source.read().strip()
    except (OSError, UnicodeError) as exc:
        raise RegistryError(f"cannot read boot identity: {exc}") from exc
    if not _BOOT_ID.fullmatch(boot_id):
        raise RegistryError("boot identity is not a well-formed UUID")
    return boot_id


def _check_components(path: Path) -> None:
    for component in (path, *path.parents):
        if component.is_symlink():
            raise RegistryError("refusing symlinked startup path")


@contextmanager
def _locked(path: Path) -> Iterator[None]:
    """Serialise cooperating writers on a stable sibling lock file."""
    _check_components(path)
    if not path.parent.is_dir():
        raise RegistryError("startup run-record parent must already exist")
    lock = path.with_name(path.name + ".lock")
    _check_components(lock)
    fd = os.open(lock, os.O_CREAT | os.O_RDWR | os.O_CLOEXEC | os.O_NOFOLLOW, 0o600)
    try:
        metadata = os.fstat(fd)
        if not stat.S_ISREG(metadata.st_mode) or metadata.st_nlink != 1 or metadata.st_mode & 0o077:
            raise RegistryError("unsafe startup run-record lock")
        fcntl.flock(fd, fcntl.LOCK_EX)
        _check_components(path)
        current = os.stat(lock, follow_symlinks=False)
        if (current.st_dev, current.st_ino) != (metadata.st_dev, metadata.st_ino):
            raise RegistryError("startup run-record lock identity changed")
        yield
    finally:
        os.close(fd)


_RUN_KEYS = frozenset({"boot_id", "recorded_at", "reconciled", "restored", "blocked", "operator_review_required"})
_RUN_MAXES = {"restored": 64, "blocked": 64}


def _validate_run(run: object) -> dict:
    if not isinstance(run, dict) or set(run) != _RUN_KEYS:
        raise RegistryError("invalid startup run record entry")
    if not isinstance(run["boot_id"], str) or not _BOOT_ID.fullmatch(run["boot_id"]):
        raise RegistryError("invalid boot identity in startup run record")
    if not isinstance(run["recorded_at"], str):
        raise RegistryError("invalid startup run record timestamp")
    for key in ("restored", "blocked"):
        if (
            not isinstance(run[key], list)
            or len(run[key]) > _RUN_MAXES[key]
            or any(not isinstance(item, str) or not item for item in run[key])
        ):
            raise RegistryError(f"invalid startup run record {key} list")
    for key in ("reconciled", "operator_review_required"):
        if type(run[key]) is not bool:
            raise RegistryError(f"invalid startup run record {key}")
    return {
        "boot_id": run["boot_id"],
        "recorded_at": run["recorded_at"],
        "reconciled": run["reconciled"],
        "restored": sorted(run["restored"]),
        "blocked": sorted(run["blocked"]),
        "operator_review_required": run["operator_review_required"],
    }


def _load(path: Path) -> dict:
    _check_components(path)
    try:
        fd = os.open(path, os.O_RDONLY | os.O_CLOEXEC | os.O_NOFOLLOW)
        with os.fdopen(fd, "r", encoding="utf-8") as source:
            metadata = os.fstat(source.fileno())
            if not stat.S_ISREG(metadata.st_mode) or metadata.st_nlink != 1 or metadata.st_mode & 0o077:
                raise RegistryError("unsafe startup run-record store")
            document = json.load(source)
    except (OSError, ValueError, UnicodeError) as exc:
        raise RegistryError("cannot load startup run records") from exc
    if not isinstance(document, dict) or set(document) != {"version", "runs"} or not isinstance(document["runs"], list):
        raise RegistryError("invalid startup run-record store shape")
    if len(document["runs"]) > MAX_RUNS:
        raise RegistryError("startup run-record store exceeds its retained limit")
    return {"version": 1, "runs": [_validate_run(run) for run in document["runs"]]}


def _write(path: Path, document: dict) -> None:
    fd, temporary = tempfile.mkstemp(prefix=".startup-runs-", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as output:
            os.fchmod(output.fileno(), 0o600)
            json.dump(document, output, sort_keys=True, indent=2)
            output.write("\n")
            output.flush()
            os.fsync(output.fileno())
        os.replace(temporary, path)
        directory_fd = os.open(path.parent, os.O_RDONLY | os.O_DIRECTORY)
        try:
            os.fsync(directory_fd)
        finally:
            os.close(directory_fd)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def record_startup_run(path: str | Path, run: object) -> dict:
    """Append one boot run under the stable lock, or fail loudly at the cap."""
    target = Path(path).absolute()
    entry = _validate_run(run)
    with _locked(target):
        document = _load(target)
        runs = [*document["runs"], entry]
        if len(runs) > MAX_RUNS:
            raise RegistryError("startup run-record store is full; remove records deliberately")
        revised = _validate({"version": 1, "runs": runs})
        _write(target, revised)
        return revised


def read_startup_runs(path: str | Path) -> dict:
    """Load and validate the store, read-only."""
    target = Path(path).absolute()
    with _locked(target):
        return _load(target)


def _validate(document: object) -> dict:
    if not isinstance(document, dict) or set(document) != {"version", "runs"}:
        raise RegistryError("invalid startup run-record store shape")
    return {"version": 1, "runs": [_validate_run(run) for run in document["runs"]]}


def initialise_startup_runs(path: str | Path) -> dict:
    """Create an empty store only if absent; never overwrite existing state."""
    target = Path(path).absolute()
    with _locked(target):
        if target.exists() or target.is_symlink():
            raise RegistryError("startup run-record store already exists")
        document = {"version": 1, "runs": []}
        fd = os.open(target, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | os.O_CLOEXEC, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as output:
            json.dump(document, output, sort_keys=True, indent=2)
            output.write("\n")
            output.flush()
            os.fsync(output.fileno())
        return document


def _python_executable(python_executable: str | None) -> str:
    if python_executable is None:
        return "/usr/bin/python3"
    return _validate_path(python_executable, "python executable")


def render_startup_unit(
    config: object,
    config_path: str,
    *,
    python_executable: str | None = None,
    script_path: str | Path | None = None,
) -> str:
    """Render the complete service unit deterministically from a validated configuration.

    The service waits for ``network-online.target`` so its ownership observations
    describe a settled network instead of racing the event system. Credentials
    are wired through ``LoadCredential`` so private keys are never command-line
    arguments and the existing descriptor-based credential boundary stays
    intact. ``config_path`` is the installed configuration file the boot command
    reads again at run time; the same file is conditioned so a moved
    configuration fails closed instead of restoring anything.
    """
    validated = validate_startup_config(config)
    config = _validate_path(config_path, "startup configuration path")
    python = _python_executable(python_executable)
    if script_path is None:
        script_path = Path(__file__).resolve().parent.parent / "nordvpn_manage.py"
    script = _validate_path(str(script_path), "manage script path")
    conditions = [
        f"ConditionPathExists={config}",
        f"ConditionPathExists={validated['policy']}",
    ]
    credentials = "\n".join(
        f"LoadCredential=ntwg-{name}:{value}" for name, value in sorted(validated["credentials"].items())
    )
    credential_lines = [credentials] if credentials else []
    return "\n".join(
        (
            _GENERATED_MARKER,
            "",
            "[Unit]",
            "Description=Nord Tools restores persistent desired-state VPN profiles at startup.",
            f"Documentation=file:{script}",
            "Wants=network-online.target",
            "After=network-online.target",
            *conditions,
            "",
            "[Service]",
            "Type=oneshot",
            "RemainAfterExit=yes",
            *credential_lines,
            f"ExecStart={python} {script} restore-startup --config {config}",
            "",
            "[Install]",
            "WantedBy=multi-user.target",
            "",
        )
    )


def plan_install(
    config: object,
    config_path: str,
    unit_dir: str | Path,
    *,
    python_executable: str | None = None,
    script_path: str | Path | None = None,
) -> dict:
    """Describe the installation without touching any file (read-only plan)."""
    unit = render_startup_unit(config, config_path, python_executable=python_executable, script_path=script_path)
    directory = Path(unit_dir)
    _check_components(directory)
    target = directory / SERVICE_UNIT
    if target.is_symlink():
        raise RegistryError(f"refusing symlinked startup unit target: {target}")
    action = "create"
    if target.exists() or target.is_symlink():
        try:
            existing = target.read_text(encoding="utf-8")
        except (OSError, UnicodeError) as exc:
            raise RegistryError("cannot read the existing startup unit") from exc
        if not existing.startswith(_GENERATED_MARKER):
            raise RegistryError(f"refusing to install over a foreign file: {target}")
        action = "unchanged" if existing == unit else "replace"
    return {
        "version": 1,
        "mode": "startup_install_plan",
        "network_changes_applied": False,
        "executed": False,
        "action": action,
        "unit_name": SERVICE_UNIT,
        "unit_path": str(target),
        "unit": unit,
    }


def install_startup_unit(
    config: object,
    config_path: str,
    unit_dir: str | Path,
    *,
    python_executable: str | None = None,
    script_path: str | Path | None = None,
    execute: bool = False,
) -> dict:
    """Install the rendered unit atomically. Only the restoration unit is touched.

    A previously generated unit is replaced atomically; a foreign file is
    refused rather than overwritten. Without ``execute``, the result is the
    read-only plan. Repeated installation is idempotent.
    """
    plan = plan_install(config, config_path, unit_dir, python_executable=python_executable, script_path=script_path)
    if not execute:
        return plan
    directory = Path(unit_dir)
    _check_components(directory)
    if not directory.is_dir():
        raise RegistryError("startup unit directory must already exist")
    target = directory / SERVICE_UNIT
    if target.is_symlink():
        raise RegistryError(f"refusing symlinked startup unit target: {target}")
    fd, temporary = tempfile.mkstemp(prefix=".startup-unit-", dir=directory)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as output:
            os.fchmod(output.fileno(), 0o644)
            output.write(plan["unit"])
            output.flush()
            os.fsync(output.fileno())
        os.replace(temporary, target)
        directory_fd = os.open(directory, os.O_RDONLY | os.O_DIRECTORY)
        try:
            os.fsync(directory_fd)
        finally:
            os.close(directory_fd)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)
    return {**plan, "executed": True, "action": "install" if plan["action"] == "create" else plan["action"]}
